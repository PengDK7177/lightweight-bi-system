def _metric_from_vat_summary(vat_df: pd.DataFrame | None, metric_name: str) -> float:
    """
    从 VAT 汇总表中读取指定指标值；若不存在则返回 0。
    Read a specific metric from VAT summary; return 0 when missing.
    """
    if vat_df is None or getattr(vat_df, "empty", True):
        return 0.0

    src = vat_df.copy()
    if "metric" not in src.columns or "value" not in src.columns:
        return 0.0

    hit = src[src["metric"] == metric_name]
    if hit.empty:
        return 0.0
    return float(pd.to_numeric(hit["value"], errors="coerce").fillna(0).iloc[0])


def _safe_count_from_frequency(freq_df: pd.DataFrame | None) -> int:
    """
    从客户频次分析结果中汇总订单数。
    Aggregate order count from customer frequency analysis output.
    """
    if freq_df is None or getattr(freq_df, "empty", True):
        return 0
    return int(pd.to_numeric(freq_df["payment_count"], errors="coerce").fillna(0).sum())


def _safe_count_from_rfm(rfm_df: pd.DataFrame | None) -> int:
    """
    从 RFM 明细表中汇总订单数（frequency 之和）。
    Aggregate full order count from detailed RFM output (sum of frequency).
    """
    if rfm_df is None or getattr(rfm_df, "empty", True):
        return 0
    if "frequency" not in rfm_df.columns:
        return 0
    return int(pd.to_numeric(rfm_df["frequency"], errors="coerce").fillna(0).sum())

