# Display the page title
st.title("Dashboard")

# 说明：Dashboard 仅可视化 Analytics 页面已经计算并保存的结果
# Note: Dashboard only visualises results that have been computed and saved by the Analytics page
st.caption("This dashboard reads outputs generated in Analytics. Run analyses there first, then return here for visualisation.")

# 从会话状态读取 Analytics 的结果数据（而非在 Dashboard 重新计算）
# Read analysis outputs from session state (instead of recalculating in Dashboard)
vat_summary_df = st.session_state.get("vat_summary_df")
cash_flow_df = st.session_state.get("cash_flow_df")
customer_freq_df = st.session_state.get("customer_payment_frequency_df")
status_dist_df = st.session_state.get("payment_status_distribution_df")
rfm_summary_df = st.session_state.get("rfm_summary_df")
rfm_result_df = st.session_state.get("rfm_result_df")


def _normalize_two_col_df(raw_df: pd.DataFrame | None, col1: str, col2: str) -> pd.DataFrame:
    """
    将任意两列表标准化为指定列名，兼容旧会话数据结构。
    Normalize any two-column table to target column names for legacy session compatibility.
    """
    if raw_df is None or getattr(raw_df, "empty", True):
        return pd.DataFrame(columns=[col1, col2])

    out = raw_df.copy()
    if len(out.columns) < 2:
        return pd.DataFrame(columns=[col1, col2])

    out = out.iloc[:, :2].copy()
    out.columns = [col1, col2]
    return out


# 兼容历史结构：确保绘图前列名一致
# Legacy compatibility: enforce consistent column names before plotting
customer_freq_df = _normalize_two_col_df(customer_freq_df, "customer", "payment_count")
status_dist_df = _normalize_two_col_df(status_dist_df, "payment_status", "count")

# 检查是否至少有一个分析结果可供可视化
# Check whether at least one analysis output is available for visualisation
if all(
    x is None or getattr(x, "empty", True)
    for x in [vat_summary_df, cash_flow_df, customer_freq_df, status_dist_df, rfm_summary_df, rfm_result_df]
):
    st.warning("No analytics outputs found. Please run analyses on the Analytics page first.")
    st.stop()

