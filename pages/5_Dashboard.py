def _normalize_two_col_df(raw_df: pd.DataFrame | None, col1: str, col2: str) -> pd.DataFrame:
    """
    将任意两列表标准化为指定列名，兼容旧会话数据结构。
    Normalize any two-column table to target column names for legacy session compatibility.
    """
    if raw_df is None or getattr(raw_df, "empty", True):
        return pd.DataFrame(columns=[col1, col2])

    out = raw_df.copy()
    if len(out.columns) < 2:
        return pd.DataFrame(columns=[col1, col2])

    out = out.iloc[:, :2].copy()
    out.columns = [col1, col2]
    return out


