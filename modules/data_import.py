# 引入 os 模块，用于检查文件是否存在及拼接路径
# Import os for checking file existence and constructing file paths
import os

# 引入 pandas，用于读取 CSV / Excel 文件并返回 DataFrame
# Import pandas for reading CSV/Excel files and returning DataFrames
import pandas as pd


def load_csv(file_or_path) -> pd.DataFrame:
    """
    从 Streamlit 上传文件对象或本地路径加载数据，支持 CSV 和 Excel 格式。
    Load data from a Streamlit UploadedFile object or a local file path; supports CSV and Excel.
    """
    # 若传入值为 None 则立即抛出异常，避免后续对空对象操作
    # Raise immediately if no file is provided to prevent downstream NoneType errors
    if file_or_path is None:
        raise ValueError("No file provided.")

    # 分支 1：处理 Streamlit UploadedFile 对象（具有 .name 属性）
    # Branch 1: handle a Streamlit UploadedFile object (identified by the presence of a .name attribute)
    if hasattr(file_or_path, "name"):
        name = file_or_path.name.lower()

        # 根据文件扩展名选择对应的 pandas 读取函数
        # Choose the appropriate pandas reader based on the file extension
        if name.endswith(".csv"):
            return pd.read_csv(file_or_path)
        if name.endswith(".xlsx") or name.endswith(".xls"):
            return pd.read_excel(file_or_path)

        # 扩展名不支持时抛出明确错误，指导用户上传正确格式
        # Raise a clear error for unsupported extensions to guide the user
        raise ValueError("Unsupported file type. Please upload CSV or Excel.")
    else:
        # 分支 2：处理本地文件系统路径（字符串）
        # Branch 2: handle a local filesystem path (string)
        path = str(file_or_path)

        # 文件不存在时抛出 FileNotFoundError，提示具体路径
        # Raise FileNotFoundError with the path if the file does not exist on disk
        if not os.path.exists(path):
            raise FileNotFoundError(f"File not found: {path}")

        # 按扩展名选择读取方式
        # Select the reader based on the file extension
        if path.lower().endswith(".csv"):
            return pd.read_csv(path)
        if path.lower().endswith(".xlsx") or path.lower().endswith(".xls"):
            return pd.read_excel(path)

        # 不支持的扩展名时给出提示
        # Raise an error for unsupported local file extensions
        raise ValueError("Unsupported file type. Please use CSV or Excel.")


